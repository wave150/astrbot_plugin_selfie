def sleep_photo(kind, expression="睡眼惺忪，眼睛半睁半闭"):
    """返回这一张睡觉照片的构图/动作/光线（供统一覆写逻辑使用）。"""
    kind = str(kind or "").strip()
    spec = _specs().get(kind) or _specs()["bed"]
    return {
        "source": "sleep",
        "intro": SELFIE_SHOT_INTRO,
        "framing": spec["framing"],
        "pose": spec["pose"],
        "face_line": spec["face"].format(expression=expression),
        "light_line": spec["light"],
        "tail": "；这是一张已经躺下睡觉的照片：被子（或外套）要盖住身体，"
                "画面里不要出现手机、自拍杆，也不要画成坐在床上或站着拍。",
        "custom_text": "这一张拍的是她睡着以后的样子：" + spec["framing"]
                       + spec["pose"] + spec["face"].format(expression=expression)
                       + spec["light"],
    }


def sleep_cue(kind):
    """生图测试「睡觉」动作来源：拼成一段可直接当动作提示词/测试 cue 的文字。"""
    photo = sleep_photo(kind)
    return ("这一张拍的是她睡着以后的样子，时间在凌晨（00:30 之后），"
            "房间里已经关灯：" + photo["framing"] + photo["pose"]
            + photo["face_line"] + photo["light_line"]
            + "画面里不要出现手机或自拍杆，也不要画成开着床头灯的卧室。")
